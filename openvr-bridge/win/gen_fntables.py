#!/usr/bin/env python3
"""Generates C function tables ("FnTable:IVRSystem_022" etc.) from openvr.h.

Unity's OpenVR plugin (openvr_api.cs) asks for FnTable interfaces: plain arrays of function
pointers in the same order as the C++ virtual methods. Each generated thunk forwards to the
C++ implementation. Usage: gen_fntables.py openvr.h out.inc
"""
import re
import sys

IMPLEMENTED = {
    "IVRSystem": "qss::System()",
    "IVRCompositor": "qss::Compositor()",
    "IVRInput": "qss::Input()",
    "IVRChaperone": "qss::Chaperone()",
}


def methods(header, cls):
    m = re.search(r"class " + cls + r"\s*\n\s*\{(.*?)\n\s*\};", header, re.S)
    if not m:
        raise SystemExit("class %s not found" % cls)
    out = []
    for decl in re.findall(r"virtual\s+(.*?)\)\s*(?:const\s*)?=\s*0\s*;", m.group(1), re.S):
        decl = re.sub(r"\s+", " ", decl).strip() + ")"
        decl = re.sub(r"VR_ARRAY_COUNT\s*\([^)]*\)", "", decl)
        decl = re.sub(r"VR_OUT_STRING\s*\(\s*\)", "", decl)
        decl = re.sub(r"VR_OUT_BUFFER_COUNT\s*\([^)]*\)", "", decl)
        decl = re.sub(r"VR_OUT_STRING_COUNT\s*\([^)]*\)", "", decl)
        head, params = decl.split("(", 1)
        params = params[:-1].strip()
        name = head.split()[-1].lstrip("*")
        ret = head[: head.rfind(name)].strip()
        plist = []
        if params and params != "void":
            depth, cur = 0, ""
            for ch in params:
                if ch == "," and depth == 0:
                    plist.append(cur)
                    cur = ""
                    continue
                depth += ch in "(<"
                depth -= ch in ")>"
                cur += ch
            plist.append(cur)
        clean = []
        for p in plist:
            p = p.split("=")[0].strip()
            pname = re.findall(r"[A-Za-z_][A-Za-z0-9_]*", p)[-1]
            clean.append((p, pname))
        out.append((ret, name, clean))
    return out


def main():
    header = open(sys.argv[1]).read()
    lines = ["// Generated by gen_fntables.py from openvr.h. Do not edit.", "namespace vr {"]
    for cls, getter in IMPLEMENTED.items():
        ms = methods(header, cls)
        names = []
        for ret, name, params in ms:
            fn = "ft_%s_%s" % (cls, name)
            names.append(fn)
            decl = ", ".join(p for p, _ in params)
            args = ", ".join(n for _, n in params)
            body = "return %s->%s(%s);" % (getter, name, args)
            lines.append("static %s __stdcall %s(%s) { %s }" % (ret, fn, decl, body))
        lines.append("static void* g_fntable_%s[] = {" % cls)
        lines += ["    (void*)&%s," % n for n in names]
        lines.append("};")
    lines.append("}  // namespace vr")
    open(sys.argv[2], "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
